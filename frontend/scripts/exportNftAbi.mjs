// Copies the Place NFT launchpad ABIs (PlaceNftFactory, PlaceNftCollection, PlaceNftSwapper, PlacePriceGuard) from
// the place-contracts Foundry build into src/launch/nftAbi.js. Run after changing an NFT contract:
//   (cd ../../place-contracts && forge build) && node scripts/exportNftAbi.mjs [path/to/place-contracts/out]
import { readFileSync, writeFileSync } from 'node:fs';

const out = process.argv[2] || '../../place-contracts/out';
const contracts = {
  NFT_FACTORY_ABI: 'PlaceNftFactory.sol/PlaceNftFactory.json',
  NFT_COLLECTION_ABI: 'PlaceNftCollection.sol/PlaceNftCollection.json',
  NFT_SWAPPER_ABI: 'PlaceNftSwapper.sol/PlaceNftSwapper.json',
  PRICE_GUARD_ABI: 'PlacePriceGuard.sol/PlacePriceGuard.json',
};

let js = '// Generated by scripts/exportNftAbi.mjs from place-contracts/out. Do not edit by hand.\n';
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(`${out}/${file}`, 'utf8'));
  js += `\nexport const ${name} = ${JSON.stringify(abi.filter((x) => x.type !== 'constructor'))};\n`;
}
writeFileSync('src/launch/nftAbi.js', js);
console.log('src/launch/nftAbi.js written');
