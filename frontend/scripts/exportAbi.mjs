// Copies the Place contract ABIs from the Foundry build (contracts/out) into src/place/abi.js.
// Run after changing a contract:  (cd ../contracts && forge build) && node scripts/exportAbi.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const out = '../contracts/out';
const contracts = {
  PLACE_HUB_ABI: 'PlaceHub.sol/PlaceHub.json',
  PLACE_CONFIG_ABI: 'PlaceConfig.sol/PlaceConfig.json',
  NFT_FACTORY_ABI: 'NftFactory.sol/NftFactory.json',
  CLUB_NFT_ABI: 'ClubNFT.sol/ClubNFT.json',
};

let js = '// Generated by scripts/exportAbi.mjs from contracts/out. Do not edit by hand.\n';
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(`${out}/${file}`, 'utf8'));
  js += `\nexport const ${name} = ${JSON.stringify(abi)};\n`;
}
writeFileSync('src/place/abi.js', js);
console.log('src/place/abi.js written');
