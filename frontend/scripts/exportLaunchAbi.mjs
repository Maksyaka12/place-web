// Copies the Place Launch ABIs from the place-contracts Foundry build into src/launch/abi.js.
// ABIs of older releases that are still indexed (0.1.0-testnet, 0.2.0-testnet) live in src/launch/abi.legacy.js:
// before exporting a release whose events change, copy what the indexer needs of the old one there first.
// Run after changing a launch contract:
//   (cd ../../place-contracts && forge build) && node scripts/exportLaunchAbi.mjs [path/to/place-contracts/out]
import { readFileSync, writeFileSync } from 'node:fs';

const out = process.argv[2] || '../../place-contracts/out';
const contracts = {
  LAUNCH_FACTORY_ABI: 'PlaceLaunchFactory.sol/PlaceLaunchFactory.json',
  LAUNCH_HOOK_ABI: 'PlaceLaunchHook.sol/PlaceLaunchHook.json',
  CREATOR_VAULT_ABI: 'PlaceCreatorVault.sol/PlaceCreatorVault.json',
  FEE_ESCROW_ABI: 'FeeEscrow.sol/FeeEscrow.json',
  ANNOUNCEMENT_REGISTRY_ABI: 'AnnouncementRegistry.sol/AnnouncementRegistry.json',
  X_RECIPIENT_REGISTRY_ABI: 'XRecipientRegistry.sol/XRecipientRegistry.json',
  LAUNCH_BUY_ADAPTER_ABI: 'PlaceLaunchBuyAdapter.sol/PlaceLaunchBuyAdapter.json',
  LAUNCH_TOKEN_ABI: 'PlaceLaunchToken.sol/PlaceLaunchToken.json',
  B20_FACTORY_ABI: 'IB20.sol/IB20Factory.json',
  PLACE_STAKING_ABI: 'PlaceStaking.sol/PlaceStaking.json',
  REWARD_TOKEN_REGISTRY_ABI: 'PlaceRewardTokenRegistry.sol/PlaceRewardTokenRegistry.json',
  REWARDS_DISTRIBUTOR_ABI: 'PlaceRewardsDistributor.sol/PlaceRewardsDistributor.json',
  COMMUNITY_VAULT_ABI: 'PlaceCommunityVault.sol/PlaceCommunityVault.json',
};
// Only the pieces of the Uniswap v4 PoolManager the indexer and API use.
const POOL_MANAGER_PICK = ['Swap', 'Initialize', 'extsload'];

let js = '// Generated by scripts/exportLaunchAbi.mjs from place-contracts/out. Do not edit by hand.\n';
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(`${out}/${file}`, 'utf8'));
  js += `\nexport const ${name} = ${JSON.stringify(abi)};\n`;
}
const pm = JSON.parse(readFileSync(`${out}/IPoolManager.sol/IPoolManager.json`, 'utf8')).abi.filter((x) => POOL_MANAGER_PICK.includes(x.name));
js += `\nexport const POOL_MANAGER_ABI = ${JSON.stringify(pm)};\n`;
// The linked library emits through the factory (delegatecall), e.g. CreatorVaultCreated: its events belong to the factory.
const ops = JSON.parse(readFileSync(`${out}/PlaceLaunchOperations.sol/PlaceLaunchOperations.json`, 'utf8')).abi.filter((x) => x.type === 'event');
js += `\nexport const LAUNCH_OPERATIONS_EVENTS = ${JSON.stringify(ops)};\n`;
writeFileSync('src/launch/abi.js', js);
console.log('src/launch/abi.js written');
